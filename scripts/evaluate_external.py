"""Score the anomaly detector on a capture you did NOT generate.

You supply the ground truth as the attacker IP address(es) published with the dataset
(for example CIC-IDS2017's documentation lists attacker and victim machines). A flow
counts as an attack when either end is an attacker IP; every other flow counts as
benign. Alerts are flows scored medium or high.

    python scripts/evaluate_external.py slice.pcap --attacker-ip 172.16.0.1
    python scripts/evaluate_external.py monday.pcap            # benign-only: false-alarm rate

Writes reports/external_evaluation.md. Report whatever it says, even if it is poor.
"""

from __future__ import annotations

import argparse
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from pcap_reader import MAX_CAPTURE_FLOWS, MAX_CAPTURE_PACKETS, read_capture  # noqa: E402
from pipeline import AnalysisPipeline  # noqa: E402

ALERT_SEVERITIES = {"medium", "high"}


def evaluate(capture_bytes: bytes, attacker_ips: set[str]) -> dict:
    """Return confusion counts and rates for one capture."""
    result = AnalysisPipeline().analyze(capture_bytes, filename="external.pcap")
    data = read_capture(capture_bytes, max_packets=MAX_CAPTURE_PACKETS, max_flows=MAX_CAPTURE_FLOWS)
    endpoints = {record.flow_id: (record.flow.client_ip, record.flow.server_ip) for record in data.flows}

    tp = fp = fn = tn = 0
    missed: list[str] = []
    rule_alerts: Counter = Counter()
    model_only_alerts = rule_alerts_total = 0
    for flow in result["flows"]:
        client, server = endpoints[flow["flow_id"]]
        is_attack = client in attacker_ips or server in attacker_ips
        alerted = flow["severity"] in ALERT_SEVERITIES
        if alerted:
            codes = {hit["code"] for hit in flow["rule_hits"]}
            rule_alerts.update(codes)
            if codes:
                rule_alerts_total += 1
            else:
                model_only_alerts += 1
        if is_attack and alerted:
            tp += 1
        elif is_attack:
            fn += 1
            missed.append(flow["flow_id"])
        elif alerted:
            fp += 1
        else:
            tn += 1
    attacks, benign = tp + fn, fp + tn
    return {
        "flows": len(result["flows"]), "packets": result["summary"]["packets_read"],
        "truncated": result["summary"]["truncated"], "attack_flows": attacks,
        "benign_flows": benign, "tp": tp, "fp": fp, "fn": fn, "tn": tn,
        "recall": tp / attacks if attacks else None,
        "precision": tp / (tp + fp) if (tp + fp) else None,
        "false_alarm_rate": fp / benign if benign else None,
        "alerts_from_rules": rule_alerts_total,
        "alerts_model_only": model_only_alerts,
        "rule_counts": dict(rule_alerts.most_common()),
    }


def _pct(value) -> str:
    return "n/a" if value is None else f"{100 * value:.1f}%"


def render_report(name: str, attackers: set[str], stats: dict) -> str:
    lines = [
        "# External anomaly evaluation", "",
        f"- Capture: `{name}` ({stats['packets']:,} packets read, {stats['flows']:,} flows"
        + (", truncated at the packet cap" if stats["truncated"] else "") + ")",
        f"- Ground truth: flows touching {', '.join(sorted(attackers)) or 'no attacker IP (benign-only run)'}",
        "- Alert = medium or high severity. This capture was not generated by this project.", "",
        "| Measure | Value |", "| --- | ---: |",
        f"| Attack flows / benign flows | {stats['attack_flows']:,} / {stats['benign_flows']:,} |",
        f"| Recall (attack flows alerted) | {_pct(stats['recall'])} |",
        f"| Precision (alerts that were attacks) | {_pct(stats['precision'])} |",
        f"| False-alarm rate (benign flows alerted) | {_pct(stats['false_alarm_rate'])} |",
        f"| TP / FP / FN / TN | {stats['tp']} / {stats['fp']} / {stats['fn']} / {stats['tn']} |", "",
        "Why flows alerted (all alerted flows, attack or benign):", "",
        f"- Flagged by at least one fixed rule: {stats['alerts_from_rules']}",
        f"- Flagged by the anomaly model alone: {stats['alerts_model_only']}",
        *[f"- Rule `{code}`: {count} flows" for code, count in stats["rule_counts"].items()], "",
        "Limits: one capture, flow-level labels derived from IP addresses, so benign flows "
        "that happen to involve an attacker machine are counted as attacks. Treat the numbers "
        "as a first external check, not a benchmark.", "",
    ]
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("capture", type=Path)
    parser.add_argument("--attacker-ip", action="append", default=[], help="Repeat for several")
    parser.add_argument("--output", type=Path, default=ROOT / "reports" / "external_evaluation.md")
    args = parser.parse_args()
    if not args.capture.is_file():
        raise SystemExit(f"{args.capture} not found.")
    attackers = set(args.attacker_ip)
    stats = evaluate(args.capture.read_bytes(), attackers)
    report = render_report(args.capture.name, attackers, stats)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(report, encoding="utf-8")
    print(report)
    print(f"[external] Wrote {args.output}")


if __name__ == "__main__":
    main()
